const uint8_t *font_glyph(char c) {
    if (c >= ' ' && c <= 'Z') {
        static const uint8_t *const table[] = {
            glyph_space, glyph_excl,  glyph_dblq,  glyph_hash,  glyph_dlr,
            glyph_perc,  glyph_amp,   glyph_squo,  glyph_lpar,  glyph_rpar,
            glyph_ast,   glyph_plus,  glyph_comma, glyph_minus, glyph_period,
            glyph_slash, glyph_n0,    glyph_n1,    glyph_n2,    glyph_n3,
            glyph_n4,    glyph_n5,    glyph_n6,    glyph_n7,    glyph_n8,
            glyph_n9,    glyph_colon, glyph_semc,  glyph_less,  glyph_equal,
            glyph_greater, glyph_ques, glyph_at,   glyph_A,     glyph_B,
            glyph_C,     glyph_D,     glyph_E,     glyph_F,     glyph_G,
            glyph_H,     glyph_I,     glyph_J,     glyph_K,     glyph_L,
            glyph_M,     glyph_N,     glyph_O,     glyph_P,     glyph_Q,
            glyph_R,     glyph_S,     glyph_T,     glyph_U,     glyph_V,
            glyph_W,     glyph_X,     glyph_Y,     glyph_Z,
        };
        return table[(uint8_t)c - ' '];
    }
    return 0;
}

static inline void putp(uint64_t x, uint64_t y, uint32_t color) {
    (void)gfx_put_pixel(x, y, color);
}

uint64_t font_draw_text(uint64_t x, uint64_t y, const char *s, uint32_t color) {
    uint64_t cx = x;
    while (*s) {
        const uint8_t *glyph = font_glyph(*s);
        if (glyph) {
            for (uint32_t col = 0; col < FONT_CW; col++) {
                uint8_t bits = glyph[col];
                for (uint32_t row = 0; row < FONT_CH; row++) {
                    if (bits & (1U << row)) {
                        putp(cx + col, y + row, color);
                    }
                }
            }
        }
        cx += FONT_CW + FONT_SP;
        s++;
    }
    return cx - x;
}

uint64_t font_text_width(const char *s) {
    uint64_t w = 0;
    while (*s) {
        if (font_glyph(*s)) {
            w += FONT_CW + FONT_SP;
        }
        s++;
    }
    if (w > 0) {
        w -= FONT_SP;
    }
    return w;
}
